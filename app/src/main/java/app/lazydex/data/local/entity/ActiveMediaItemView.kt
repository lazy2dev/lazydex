package app.lazydex.data.local.entity

import androidx.room.DatabaseView

@DatabaseView(
    viewName = "active_media_items",
    value = """
        SELECT 
            m.id,
            m.type,
            m.format,
            m.countryOfOrigin,
            m.title,
            m.titleEnglish,
            m.titleRomaji,
            m.titleNative,
            m.coverImagePath,
            m.coverImageUrl,
            m.bannerImage,
            m.description,
            m.author,
            COALESCE(u.userStatus, 'PLAN_TO') AS userStatus,
            COALESCE(u.progress, 0.0) AS progress,
            m.progressTotal,
            COALESCE(u.secondaryProgress, 0.0) AS secondaryProgress,
            m.secondaryProgressTotal,
            u.scoreRaw,
            COALESCE(u.repeat, 0) AS repeat,
            COALESCE(u.notes, '') AS notes,
            m.genres,
            m.tags,
            COALESCE(u.isPrivate, 0) AS isPrivate,
            m.isAdult,
            u.startYear,
            u.startMonth,
            u.startDay,
            u.endYear,
            u.endMonth,
            u.endDay,
            m.durationMinutes,
            m.avgChapterLength,
            m.lengthUnitOverride,
            m.playbackSpeed,
            m.createdAt,
            m.updatedAt AS catalogUpdatedAt,
            u.updatedAt AS userUpdatedAt,
            u.progressIncreasedAt,
            m.deletedAt
        FROM media_items m
        LEFT JOIN user_data u ON u.mediaId = m.id
        WHERE m.deletedAt IS NULL
    """
)
data class ActiveMediaItemView(
    val id: String,
    val type: String,
    val format: String,
    val countryOfOrigin: String?,
    val title: String,
    val titleEnglish: String?,
    val titleRomaji: String?,
    val titleNative: String?,
    val coverImagePath: String,
    val coverImageUrl: String?,
    val bannerImage: String?,
    val description: String,
    val author: String,
    val userStatus: String,
    val progress: Double,
    val progressTotal: Double?,
    val secondaryProgress: Double,
    val secondaryProgressTotal: Double?,
    val scoreRaw: Int?,
    val repeat: Int,
    val notes: String,
    val genres: String,
    val tags: String,
    val isPrivate: Boolean,
    val isAdult: Boolean,
    val startYear: Int?,
    val startMonth: Int?,
    val startDay: Int?,
    val endYear: Int?,
    val endMonth: Int?,
    val endDay: Int?,
    val durationMinutes: Int?,
    val avgChapterLength: Int?,
    val lengthUnitOverride: String?,
    val playbackSpeed: Double,
    val createdAt: Long,
    val catalogUpdatedAt: Long,
    val userUpdatedAt: Long?,
    val progressIncreasedAt: Long?,
    val deletedAt: Long?
) {
    val updatedAt: Long get() = userUpdatedAt ?: catalogUpdatedAt
}
